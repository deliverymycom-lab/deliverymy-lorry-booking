let currentLanguage: Language = 'ms';
const listeners: Array<(lang: Language) => void> = [];

export const LanguageService = {
  getLanguage: (): Language => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('appLanguage') as Language;
      if (saved && (saved === 'ms' || saved === 'en' || saved === 'zh')) {
        currentLanguage = saved;
      }
    }
    return currentLanguage;
  },

  setLanguage: (lang: Language) => {
    currentLanguage = lang;
    if (typeof window !== 'undefined') {
      localStorage.setItem('appLanguage', lang);
    }
    listeners.forEach((fn) => fn(lang));
  },

  subscribe: (fn: (lang: Language) => void) => {
    listeners.push(fn);
    return () => {
      const idx = listeners.indexOf(fn);
      if (idx !== -1) listeners.splice(idx, 1);
    };
  },

  t: (key: string, lang?: Language): string => {
    const l = lang || currentLanguage;
    const dict = translations[l] || translations.ms;
    return dict[key] || translations.en[key] || translations.ms[key] || key;
  },
};
